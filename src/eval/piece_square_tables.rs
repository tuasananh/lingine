use crate::{
    core::{PieceType, Side, Square},
    eval::packed,
};

use super::PackedScore;

#[inline]
pub(crate) const fn piece_square_table_value_tapered(
    piece_type: PieceType,
    color: Side,
    sq: Square,
) -> PackedScore {
    let index = match color {
        Side::Red => sq,
        Side::Black => sq.mirrored(),
    } as usize;
    match piece_type {
        PieceType::King => PIECE_SQUARE_TABLE_KING_TAPERED[index],
        PieceType::Advisor => PIECE_SQUARE_TABLE_ADVISOR_TAPERED[index],
        PieceType::Bishop => PIECE_SQUARE_TABLE_BISHOP_TAPERED[index],
        PieceType::Knight => PIECE_SQUARE_TABLE_KNIGHT_TAPERED[index],
        PieceType::Rook => PIECE_SQUARE_TABLE_ROOK_TAPERED[index],
        PieceType::Cannon => PIECE_SQUARE_TABLE_CANNON_TAPERED[index],
        PieceType::Pawn => PIECE_SQUARE_TABLE_PAWN_TAPERED[index],
    }
}

#[inline]
pub(in crate::eval) fn piece_square_table_value_tapered_with_params(
    piece_type: PieceType,
    color: Side,
    sq: Square,
    params: &super::EvalParams,
) -> PackedScore {
    let index = match color {
        Side::Red => sq,
        Side::Black => sq.mirrored(),
    };
    params.psts[piece_type][index]
}

