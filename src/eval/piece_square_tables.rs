#[inline]
pub const fn piece_square_table_value_tapered(
    piece_type: PieceType,
    color: Side,
    sq: Square,
) -> PackedScore {
    let index = match color {
        Side::Red => sq as usize,
        Side::Black => {
            // Mirror rank vertically: 9 - rank, and file horizontally: 8 - file
            let file = sq.file() as usize;
            let rank = sq.rank() as usize;
            let mirrored_rank = Rank::COUNT - 1 - rank;
            let mirrored_file = File::COUNT - 1 - file;
            mirrored_rank * File::COUNT + mirrored_file
        }
    };
    match piece_type {
        PieceType::King => PIECE_SQUARE_TABLE_KING_TAPERED[index],
        PieceType::Advisor => PIECE_SQUARE_TABLE_ADVISOR_TAPERED[index],
        PieceType::Bishop => PIECE_SQUARE_TABLE_BISHOP_TAPERED[index],
        PieceType::Knight => PIECE_SQUARE_TABLE_KNIGHT_TAPERED[index],
        PieceType::Rook => PIECE_SQUARE_TABLE_ROOK_TAPERED[index],
        PieceType::Cannon => PIECE_SQUARE_TABLE_CANNON_TAPERED[index],
        PieceType::Pawn => PIECE_SQUARE_TABLE_PAWN_TAPERED[index],
    }
}

#[inline]
pub fn piece_square_table_value_tapered_with_params(
    piece_type: PieceType,
    color: Side,
    sq: Square,
    params: &super::EvalParams,
) -> PackedScore {
    let index = match color {
        Side::Red => sq as usize,
        Side::Black => {
            let file = sq.file() as usize;
            let rank = sq.rank() as usize;
            let mirrored_rank = Rank::COUNT - 1 - rank;
            let mirrored_file = File::COUNT - 1 - file;
            mirrored_rank * File::COUNT + mirrored_file
        }
    };
    params.psts[piece_type as usize][index]
}
